def area(a, h):
    '''принимает в качестве аргумента сторону a, высоту h треугольника
    и возвращает площадь этого треугольника'''
    return a * h / 2 

def perimeter(a, b, c):
    '''принимает в качестве аргумента стороны a, b, c треугольника
    и возвращает периметр этого треугольника'''
    return a + b + c
