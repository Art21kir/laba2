import math


def area(r):
    '''принимает в качестве аргумента радиус окружности r и возвращает
    площадь этой окружности'''
    return math.pi * r * r


def perimeter(r):
    '''принимает в качестве аргумента радиус окружности r и возвращает
    длинну этой окружности'''
    return 2 * math.pi * r

